# Free Edition allows only ONE SQL warehouse (the pre-created starter). Instead of
# editing the committed databricks.yml, this writes a machine-local override to
# databricks/local/free-edition.yml (gitignored, merged via `include: ./local/*.yml`)
# that points the bundle's warehouse resource at the existing starter warehouse, so
# DAB updates it in place rather than creating a second warehouse.
#
# Usage: bash scripts/dbx-starter-wh.sh    (or: mise run dbx:use-starter-wh)
# Env: DATABRICKS_PROFILE (default DEFAULT), BUNDLE_DIR (default databricks)
set -euo pipefail

PROFILE="${DATABRICKS_PROFILE:-DEFAULT}"
BUNDLE_DIR="${BUNDLE_DIR:-databricks}"

WH=$(databricks sql-warehouses list --profile "$PROFILE" --output json \
  | jq -r 'first(.[] | select((.name // "") | test("starter"; "i"))) // .[0] // empty')
if [[ -z "$WH" ]]; then
  echo "ERROR: no SQL warehouse found via 'databricks sql-warehouses list'" >&2
  exit 1
fi
WH_ID=$(jq -r .id <<<"$WH")
WH_NAME=$(jq -r .name <<<"$WH")

mkdir -p "$BUNDLE_DIR/local"
cat > "$BUNDLE_DIR/local/free-edition.yml" <<EOF
# Generated by: mise run dbx:use-starter-wh  (machine-local, gitignored)
# Free Edition allows only one warehouse; point the bundle's warehouse resource at
# the pre-created starter so DAB updates it instead of creating a new one.
resources:
  sql_warehouses:
    streetlights_wh:
      name: "$WH_NAME"
      cluster_size: 2X-Small
      enable_serverless_compute: true
      auto_stop_mins: 30
EOF

echo "wrote $BUNDLE_DIR/local/free-edition.yml (warehouse '$WH_NAME' id=$WH_ID)"
echo "committed databricks.yml untouched; git status stays clean"
echo "next: cd $BUNDLE_DIR && databricks bundle validate -t dev && databricks bundle deploy -t dev"
